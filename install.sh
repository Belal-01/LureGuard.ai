printf '\n'
# A core API that never answers is a failed install, not a warning. Reporting it
# as a warning and then printing "LureGuard is running." at the end sends the
# user to a dashboard with nothing behind it, and exits 0 so any automation
# wrapping this script believes the install worked.
[ "$READY" = 1 ] || die "Core API did not come up within 2 minutes."
