# ── cleanup ───────────────────────────────────────────────────────────────────
# Undo whatever this run created if it does not reach the end — including on
# Ctrl-C, which otherwise leaves a half-finished clone and half-created
# containers behind and makes the next run look like a corrupted install.
#
# The cut-off is `docker compose up -d` succeeding. Before that point nothing
# the user can inspect exists yet, so a failure removes the partial state. After
# it, the containers ARE the diagnostic — tearing them down would delete the
# logs needed to find out why the install failed — so cleanup keeps its hands
# off and prints how to inspect and how to remove them instead.
#
# CREATED_DIR is only ever set to a directory this run cloned itself, so an
# existing checkout is never a candidate for removal.
CREATED_DIR=""
STARTED_STACK=0
INSTALL_OK=0
# `trap 'exit 130' INT` does not survive into the EXIT trap: $? reads 0 there,
# so an interrupted install would report success to whatever called it. The
# signal handlers record the code themselves instead of relying on $?.
EXIT_CODE=""

cleanup() {
  status=$?
  [ -n "$EXIT_CODE" ] && status="$EXIT_CODE"
  [ "$INSTALL_OK" = 1 ] && exit "$status"
  [ "$STARTED_STACK" = 0 ] && [ -z "$CREATED_DIR" ] && exit "$status"

  printf '\n'
  if [ "$STARTED_STACK" = 1 ]; then
    ui_warn "The services are still running so you can read their logs:"
    ui_cmd "cd $INSTALL_DIR && docker compose logs"
    ui_hint "To remove them: cd $INSTALL_DIR && docker compose down -v"
  else
    # shellcheck disable=SC2086
    [ -f "$INSTALL_DIR/docker-compose.yml" ] && \
      (cd "$INSTALL_DIR" && docker compose ${COMPOSE_ARGS:-} down --remove-orphans >/dev/null 2>&1) || true
    if [ -n "$CREATED_DIR" ] && [ -d "$CREATED_DIR" ]; then
      ui_info "Removing the partial checkout at $CREATED_DIR"
      cd / && rm -rf "$CREATED_DIR"
    fi
  fi
  printf '\n'
  exit "$status"
}
trap cleanup EXIT
trap 'EXIT_CODE=130; exit 130' INT
trap 'EXIT_CODE=143; exit 143' TERM

# ── prompts ───────────────────────────────────────────────────────────────────
# `curl ... | sh` leaves stdin pointing at the pipe, so read from the terminal
# directly when there is one. With no terminal at all we take the defaults
# rather than hanging forever waiting for input that cannot arrive.
TTY=""
[ -e /dev/tty ] && [ -r /dev/tty ] && TTY=/dev/tty

interactive() { [ "$ASSUME_YES" != 1 ] && [ -n "$TTY" ]; }

ask_yes_no() {  # $1 question, $2 default(y/n) -> echoes y|n
  local q="$1" def="$2" ans hint
  if [ "$ASSUME_YES" = 1 ] || [ -z "$TTY" ]; then echo "$def"; return; fi
  [ "$def" = y ] && hint="Y/n" || hint="y/N"
  printf '  %s?%s %s %s[%s]%s ' "$C_CYAN" "$C_RESET" "$q" "$C_GREY" "$hint" "$C_RESET" > "$TTY"
  read -r ans < "$TTY" || ans=""
  case "${ans:-$def}" in [Yy]*) echo y ;; *) echo n ;; esac
}

ask_value() {  # $1 question, $2 default -> echoes value
  local q="$1" def="$2" ans
  if [ "$ASSUME_YES" = 1 ] || [ -z "$TTY" ]; then echo "$def"; return; fi
  if [ -n "$def" ]; then
    printf '  %s?%s %s %s[%s]%s ' "$C_CYAN" "$C_RESET" "$q" "$C_GREY" "$def" "$C_RESET" > "$TTY"
  else
    printf '  %s?%s %s ' "$C_CYAN" "$C_RESET" "$q" > "$TTY"
  fi
  read -r ans < "$TTY" || ans=""
  echo "${ans:-$def}"
}

gen_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 24
  elif [ -r /dev/urandom ]; then
    LC_ALL=C tr -dc 'a-f0-9' < /dev/urandom | head -c 48
  else
    die "No source of randomness (need openssl or /dev/urandom) — refusing to generate weak secrets."
  fi
}

port_busy() {
  if command -v lsof >/dev/null 2>&1; then
    lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1
  elif command -v ss >/dev/null 2>&1; then
    ss -ltn 2>/dev/null | awk '{print $4}' | grep -qE "[:.]$1\$"
  else
    return 1   # cannot tell; do not block the install on a missing tool
  fi
}

port_owner() {
  command -v lsof >/dev/null 2>&1 || { echo "unknown process"; return; }
  lsof -nP -iTCP:"$1" -sTCP:LISTEN 2>/dev/null | awk 'NR==2{print $1" (pid "$2")"}'
}

# A port held by our own stack is a re-run, not a conflict. Without this the
# installer refuses to upgrade an existing install because it collides with
# itself — and the port owner reads as the Docker runtime (OrbStack, Docker
# Desktop), which tells the user nothing about what to stop.
port_is_ours() {
  docker ps --filter "publish=$1" --format '{{.Label "com.docker.compose.project"}}' 2>/dev/null \
    | grep -qi 'lureguard'
}

