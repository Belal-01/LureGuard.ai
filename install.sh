stage() {
  STAGE=$((STAGE + 1))
  printf '\n%s%s[%d/%d]%s %s%s%s\n' \
    "$C_BOLD" "$C_CYAN" "$STAGE" "$STAGE_TOTAL" "$C_RESET" "$C_BOLD" "$1" "$C_RESET"
